SANS = 'var(--md-text-font-family, system-ui, -apple-system, "Segoe UI", Roboto, Helvetica, Arial, sans-serif)'
MONO = 'var(--md-code-font-family, ui-monospace, SFMono-Regular, Menlo, Consolas, monospace)'


def _vars(mode):
    return ";".join(f"--kx-{k}:{v[mode]}" for k, v in TOKENS.items())


def figure_css():
    """Style for the site: the variables follow the theme toggle of Material."""
    return ("/* Generated by tools/make_figures.py */\n"
            f'[data-md-color-scheme="default"] .kxfig {{{_vars(0)}}}\n'
            f'[data-md-color-scheme="slate"] .kxfig {{{_vars(1)}}}\n'
            ".kxfig-wrap {margin: 1.5em 0; text-align: center}\n"
            ".kxfig-wrap svg {max-width: 100%; height: auto}\n")


class Fig:
    """A small SVG builder. ``flat`` = 0 or 1 writes plain colours of that mode
    (previews); ``None`` writes classes and CSS variables."""

    def __init__(self, w, h, title, flat=None):
        self.w, self.h, self.title, self.flat, self.items = w, h, title, flat, []

    def _paint(self, attr, tok):
        if tok is None:
            return f'{attr}="none"'
        if self.flat is not None:
            return f'{attr}="{TOKENS[tok][self.flat]}"'
        return f'style="{attr}:var(--kx-{tok})"'

    def _style(self, fill, stroke, extra=""):
        parts = []
        for attr, tok in (("fill", fill), ("stroke", stroke)):
            if tok is None:
                parts.append(f"{attr}:none")
            elif self.flat is not None:
                parts.append(f"{attr}:{TOKENS[tok][self.flat]}")
            else:
                parts.append(f"{attr}:var(--kx-{tok})")
        return f'style="{";".join(parts)}{";" + extra if extra else ""}"'

    def rect(self, x, y, w, h, fill="panel", stroke=None, sw=1, rx=0, dash=None, opacity=None):
        extra = f"stroke-width:{sw}" + (f";stroke-dasharray:{dash}" if dash else "")
        extra += f";opacity:{opacity}" if opacity is not None else ""
        self.items.append(f'<rect x="{x:g}" y="{y:g}" width="{w:g}" height="{h:g}" rx="{rx:g}" '
                          f'{self._style(fill, stroke, extra)}/>')

    def circle(self, x, y, r, fill="c1", stroke=None, sw=1):
        self.items.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{r:g}" {self._style(fill, stroke, f"stroke-width:{sw}")}/>')

    def line(self, x1, y1, x2, y2, stroke="line", sw=1, dash=None):
        extra = f"stroke-width:{sw}" + (f";stroke-dasharray:{dash}" if dash else "")
        self.items.append(f'<line x1="{x1:g}" y1="{y1:g}" x2="{x2:g}" y2="{y2:g}" '
                          f'{self._style(None, stroke, extra)}/>')

    def dots(self, pts, r, color):
        """Many small dots as one path of zero-length round-capped segments."""
        d = "".join(f"M{x:.1f} {y:.1f}h0" for x, y in pts)
        self.items.append(f'<path d="{d}" {self._style(None, color, f"stroke-width:{2 * r:g};stroke-linecap:round")}/>')

    def segments(self, segs, color, sw=1):
        d = "".join(f"M{x1:.1f} {y1:.1f}L{x2:.1f} {y2:.1f}" for x1, y1, x2, y2 in segs)
        self.items.append(f'<path d="{d}" {self._style(None, color, f"stroke-width:{sw:g}")}/>')

    def boxes(self, rects, color):
        d = "".join(f"M{x:.2f} {y:.2f}h{w:.2f}v{h:.2f}h{-w:.2f}z" for x, y, w, h in rects)
        self.items.append(f'<path d="{d}" {self._style(color, None)}/>')

    def path(self, d, fill=None, stroke="ink", sw=1.5, dash=None):
        extra = f"stroke-width:{sw};stroke-linejoin:round;stroke-linecap:round"
        extra += f";stroke-dasharray:{dash}" if dash else ""
        self.items.append(f'<path d="{d}" {self._style(fill, stroke, extra)}/>')

    def arrow(self, x1, y1, x2, y2, stroke="ink2", sw=1.5, head=7, dash=None):
        """A straight arrow ending at (x2, y2)."""
        a = math.atan2(y2 - y1, x2 - x1)
        bx, by = x2 - head * math.cos(a), y2 - head * math.sin(a)
        self.line(x1, y1, bx, by, stroke, sw, dash)
        p = [(x2, y2), (bx - head * 0.5 * math.sin(a), by + head * 0.5 * math.cos(a)),
             (bx + head * 0.5 * math.sin(a), by - head * 0.5 * math.cos(a))]
        self.items.append('<polygon points="' + " ".join(f"{u:.1f},{v:.1f}" for u, v in p) + f'" '
                          f'{self._style(stroke, None)}/>')

    def text(self, x, y, s, size=13, fill="ink", anchor="middle", weight=None, mono=False, italic=False,
             rotate=None):
        """Text; ``a_{b}`` is a subscript."""
        body, pos, low = "", 0, False
        while True:
            k = s.find("_{", pos)
            chunk = escape(s[pos:] if k < 0 else s[pos:k])
            if chunk:  # back to the baseline after a subscript
                body += f'<tspan dy="{-size * 0.3:.1f}">{chunk}</tspan>' if low else chunk
                low = False
            if k < 0:
                break
            e = s.index("}", k)
            body += f'<tspan dy="{0 if low else size * 0.3:.1f}" style="font-size:{size * 0.72:.1f}px">' \
                + escape(s[k + 2:e]) + "</tspan>"
            low = True
            pos = e + 1
        st = [f"font-family:{MONO if mono else SANS}", f"font-size:{size}px"]
        st += ["font-weight:600"] if weight else []
        st += ["font-style:italic"] if italic else []
        col = TOKENS[fill][self.flat] if self.flat is not None else f"var(--kx-{fill})"
        st.append(f"fill:{col}")
        tr = f' transform="rotate({rotate} {x:g} {y:g})"' if rotate else ""
        self.items.append(f'<text x="{x:g}" y="{y:g}" text-anchor="{anchor}"{tr} '
                          f'style=\'{";".join(st)}\'>{body}</text>')

    def svg(self):
        head = (f'<svg class="kxfig" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {self.w} {self.h}" '
                f'width="{self.w}" height="{self.h}" role="img" aria-label="{escape(self.title)}">')
        out = [head, f"<title>{escape(self.title)}</title>"]
        if self.flat is None:
            out.append(f"<style>.kxfig{{{_vars(0)}}}@media (prefers-color-scheme: dark)"
                       f"{{.kxfig{{{_vars(1)}}}}}</style>")
        else:
            out.append(f'<rect width="100%" height="100%" fill="{TOKENS["bg"][self.flat]}"/>')
        return "\n".join(out + self.items + ["</svg>"]) + "\n"



