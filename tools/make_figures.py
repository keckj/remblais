    # 2. centroids and the blocks kept for one cluster of x
    x0 = 10 + s + 34
    _frame(f, x0, top, s, "2. Coarse level: centroids", "kept clusters of y for one cluster of x")
    i = int(torch_argmin(xc, (0.27, 0.62)))
    kept = keep[i]
    for j, p in enumerate(yc):
        if bool(kept[j]):
            f.circle(*P(x0, p), 3.2, "c2")
        else:
            f.circle(*P(x0, p), 2.2, None, "c2", 0.8)
