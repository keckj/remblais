    _frame(f, x0, top, s, "3. Fine level: kept blocks", f"{100 * ratio:.0f} % of the cluster pairs are kept")
    ci, cj = keep.shape
    h, w = s / ci, s / cj
    f.rect(x0, top, s, s, "panel", None, rx=4)
    runs = {"c1": [], "c2": []}
    for a in range(ci):
        row = keep[a].tolist()
