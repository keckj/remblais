def torch_argmin(pts, target):
    d = ((pts[:, 0] - target[0]) ** 2 + (pts[:, 1] - target[1]) ** 2)
    return d.argmin()


def _schedule(D, n=100_000, blur=0.05, scaling=0.5, p=2):
    """ε schedule and cluster size of the benchmark of docs/performance.md."""
    torch = _torch()
    from remblais.sinkhorn_divergence import scaling_parameters
    g = torch.Generator().manual_seed(0)
    x = torch.rand(n, D, generator=g)
    y = 0.05 + 0.9 * torch.rand(n, D, generator=g)
    y[:, 0] += 0.2
    diameter, _, eps_list, _ = scaling_parameters(x, y, p, blur, None, None, scaling)
    cluster = diameter / (math.sqrt(D) * 2000 ** (1 / D))
    sig = [e ** (1 / p) for e in eps_list]
    jump = len(sig) - 1
    for i, e in enumerate(eps_list[2:]):
        if cluster ** p > e:
            jump = i + 1
            break
    return sig, cluster, jump, blur


