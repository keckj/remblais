def _torch():
    import torch
    torch.set_num_threads(min(8, torch.get_num_threads()))
    return torch


def _frame(f, x0, y0, s, title, sub=None):
    f.rect(x0, y0, s, s, None, "grid", 1, rx=4)
    f.text(x0 + s / 2, y0 - 12, title, 13, "ink", weight=True)
    if sub:
        f.text(x0 + s / 2, y0 + s + 20, sub, 12, "ink2")


_FLOW = None


def _flow_data():
    """The Sinkhorn flow of docs/guides/gradient-flow.md, on the CPU."""
    global _FLOW
    if _FLOW is None:
        torch = _torch()
        from remblais import SamplesLoss
        torch.manual_seed(0)
        N = M = 1_000
        x = 0.1 * torch.randn(N, 2) + 0.5
        t = 2 * math.pi * torch.rand(M)
        y = 0.5 + 0.3 * torch.stack([t.cos(), t.sin()], dim=1)
        a, b = torch.full((N,), 1 / N), torch.full((M,), 1 / M)
        loss = SamplesLoss("sinkhorn", p=2, blur=0.01, scaling=0.9)
        lr, snaps, moves = 0.25, {}, None
        x.requires_grad_()
        for step in range(13):
            L = loss(a, x, b, y)
            [g] = torch.autograd.grad(L, [x])
            if step == 0:
                moves = (-g / a[:, None]).detach().clone()
            snaps[step] = x.detach().clone()
            with torch.no_grad():
                x -= lr * g / a[:, None]
        _FLOW = (y, snaps, moves)
    return _FLOW


def fig_flow(flat=None):
    """Gradient flow of a blob onto a ring: the gradient, then two later steps."""
    y, snaps, moves = _flow_data()
    s, top = 220, 36
    f = Fig(3 * s + 2 * 30 + 20, s + top + 34, "A Sinkhorn gradient flow moves a blob of points onto a ring", flat)
    def P(x0, p):  # [0.05, 0.95]^2 -> panel, clipped to the frame
        u = min(max((float(p[0]) - 0.05) / 0.9, 0.0), 1.0)
        v = min(max((float(p[1]) - 0.05) / 0.9, 0.0), 1.0)
        return x0 + u * s, top + s - v * s
    panels = [(0, "step 0: where −∇ₓL / a points"), (4, "after 4 steps"), (12, "after 12 steps")]
    for k, (step, title) in enumerate(panels):
        x0 = 10 + k * (s + 30)
        _frame(f, x0, top, s, title)
        f.dots([P(x0, p) for p in y[::2]], 1.6, "c2")
        xs = snaps[step]
        if k == 0:
            f.segments([(*P(x0, p), *P(x0, p + v)) for p, v in list(zip(xs, moves))[::8]], "c1", 0.5)
        f.dots([P(x0, p) for p in xs[::2]], 1.6, "c1")
    f.text(10, s + top + 26, "Source x (teal), target y (orange), 1,000 points each, blur = 0.01; each step moves x by "
           "0.25 · (−∇ₓL / a).",
           12, "ink2", "start")
    return f


_MS = None


def _multiscale_data():
    """Clusters and kept blocks of the multiscale backend on two 2D clouds."""
    global _MS
    if _MS is None:
        torch = _torch()
        import remblais.sinkhorn_samples as ss
        from remblais import SamplesLoss
        g = torch.Generator().manual_seed(1)
        n = 5_000
        x = (0.09 * torch.randn(n, 2, generator=g)).clamp(-0.25, 0.25) + torch.tensor([0.4, 0.5])
        t = 2 * math.pi * torch.rand(n, generator=g)
        r = 0.33 + 0.03 * torch.randn(n, generator=g)
        y = torch.tensor([0.55, 0.5]) + r[:, None] * torch.stack([t.cos(), t.sin()], dim=1)
        calls = []
        orig = ss.kernel_truncation
        def spy(C_xy, C_yx, C_xy_, C_yx_, f_ba, g_ab, eps, truncate=None, cost=None, verbose=False):
            if not calls:
                with torch.no_grad():
                    C = cost(C_xy[0], C_xy[1])
                    keep = f_ba.view(-1, 1) + g_ab.view(1, -1) > C - truncate * eps
                calls.append((C_xy[0].detach().clone(), C_xy[1].detach().clone(), keep.clone()))
            return orig(C_xy, C_yx, C_xy_, C_yx_, f_ba, g_ab, eps, truncate=truncate, cost=cost, verbose=verbose)
        ss.kernel_truncation = spy
        try:
            SamplesLoss("sinkhorn", p=2, blur=0.01, scaling=0.5, backend="multiscale", cluster_scale=0.05)(x, y)
        finally:
            ss.kernel_truncation = orig
        _MS = (x, y) + calls[0]
    return _MS


